export function managementText(
  language: string,
  key: keyof Texts,
  values: Record<string, string | number> = {},
): string {
  const bundle = ({ en, zh, ja, ko, it } as Record<string, Texts>)[language] ?? en;
  return bundle[key].replace(/\{(\w+)\}/g, (match, name) =>
    values[name] === undefined ? match : String(values[name]),
  );
}
export type ManagementKey = keyof Texts;
